export async function seed(db) {
  if ((await db.get('SELECT COUNT(*) AS n FROM users')).n) return;
  // The editorial account has no password and cannot log in; real users register their own accounts.
  await db.transaction(async (tx) => {
    const { insertId: author } = await tx.run(
      'INSERT INTO users(name,email,bio) VALUES(?,?,?)',
      'Dapur Nusa Rasa',
      'dapur@example.invalid',
      'Kumpulan resep contoh untuk menjelajahi cita rasa Nusantara.',
    );
    for (const [i, r] of initialRecipes.entries())
      await tx.run(
        'INSERT INTO recipes(author_id,title,description,region,image,minutes,servings,ingredients,steps,created_at) VALUES(?,?,?,?,?,?,?,?,?,?)',
        author,
        r.title,
        r.description,
        r.region,
        '/assets/' + r.image,
        r.minutes,
        r.servings,
        JSON.stringify(r.ingredients),
        JSON.stringify(r.steps),
        new Date(Date.UTC(2026, 8, 20, 12, 0, 6 - i)),
      );
  });
}
